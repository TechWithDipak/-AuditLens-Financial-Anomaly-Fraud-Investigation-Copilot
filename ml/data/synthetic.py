"""Synthetic dataset generator for testing and demonstration.

IMPORTANT NOTICE:
All data generated by this module is purely synthetic. It is strictly used
for unit testing, CI/CD validation, and local developer demonstrations.
It must NEVER be presented or reported as real-world fraud performance.
"""

from pathlib import Path

import numpy as np
import pandas as pd

from ml.data.schema import PCA_COLUMNS


def generate_synthetic_transactions(
    n_samples: int = 150,
    fraud_ratio: float = 0.05,
    random_state: int = 42,
) -> pd.DataFrame:
    """Generate synthetic credit card transaction data strictly matching the schema.

    Args:
        n_samples: Total number of transactions to generate.
        fraud_ratio: Fraction of fraudulent transactions (default: 5%).
        random_state: Seed for reproducibility.

    Returns:
        pd.DataFrame: Tabular data with Time, V1-V28, Amount, and Class columns.
    """
    rng = np.random.default_rng(random_state)
    n_fraud = max(1, int(n_samples * fraud_ratio))
    n_normal = n_samples - n_fraud

    # 1. Generate elapsed time (seconds over 48 hours)
    time_normal = np.sort(rng.uniform(0, 172800, size=n_normal))
    time_fraud = np.sort(rng.uniform(0, 172800, size=n_fraud))
    time = np.concatenate([time_normal, time_fraud])

    # 2. Generate 28 PCA dimensions (normal: N(0, 1); fraud: shifted distributions)
    pca_normal = rng.standard_normal((n_normal, len(PCA_COLUMNS)))
    # Fraud cases have distinct statistical shifts on key components like V4, V11, V14
    pca_fraud = rng.standard_normal((n_fraud, len(PCA_COLUMNS)))
    pca_fraud[:, 3] += 3.5  # V4 elevated
    pca_fraud[:, 10] += 2.8  # V11 elevated
    pca_fraud[:, 13] -= 4.2  # V14 depressed
    pca_data = np.vstack([pca_normal, pca_fraud])

    # 3. Generate transaction amounts
    # Normal transactions follow log-normal distribution with low median
    amounts_normal = np.round(rng.lognormal(mean=3.2, sigma=1.2, size=n_normal), 2)
    # Fraud transactions occasionally show atypical amounts
    amounts_fraud = np.round(rng.lognormal(mean=4.0, sigma=1.5, size=n_fraud), 2)
    amounts = np.concatenate([amounts_normal, amounts_fraud])

    # 4. Target classes
    classes = np.concatenate(
        [np.zeros(n_normal, dtype=int), np.ones(n_fraud, dtype=int)]
    )

    # Construct DataFrame
    df = pd.DataFrame(pca_data, columns=PCA_COLUMNS)
    df.insert(0, "Time", np.round(time, 1))
    df["Amount"] = amounts
    df["Class"] = classes

    # Shuffle to interleave fraud and normal transactions realistically
    shuffle_idx = rng.permutation(n_samples)
    df = df.iloc[shuffle_idx].reset_index(drop=True)

    return df


def create_sample_fixtures(output_dir: str | Path = "./data/sample") -> dict[str, Path]:
    """Create sample fixtures in the specified directory for tests."""
    out_path = Path(output_dir)
    out_path.mkdir(parents=True, exist_ok=True)

    fixtures = {}

    # 1. Valid synthetic dataset
    valid_df = generate_synthetic_transactions(
        n_samples=150, fraud_ratio=0.06, random_state=42
    )
    valid_file = out_path / "synthetic_creditcard_sample.csv"
    valid_df.to_csv(valid_file, index=False)
    fixtures["valid"] = valid_file

    # 2. Corrupted fixture: missing columns
    corrupt_cols_df = valid_df[["Time", "V1", "V2", "Amount", "Class"]].copy()
    missing_file = out_path / "corrupted_missing_columns.csv"
    corrupt_cols_df.to_csv(missing_file, index=False)
    fixtures["missing_columns"] = missing_file

    # 3. Corrupted fixture: non-numeric values
    corrupt_types_df = valid_df.copy()
    corrupt_types_df.loc[0, "V1"] = "CORRUPTED_STRING_VALUE"
    corrupt_types_df.loc[1, "Amount"] = "INVALID_CURRENCY"
    corrupt_types_file = out_path / "corrupted_types.csv"
    corrupt_types_df.to_csv(corrupt_types_file, index=False)
    fixtures["corrupted_types"] = corrupt_types_file

    # 4. Corrupted fixture: negative amounts
    negative_amount_df = valid_df.copy()
    negative_amount_df.loc[5, "Amount"] = -99.99
    neg_file = out_path / "corrupted_negative_amount.csv"
    negative_amount_df.to_csv(neg_file, index=False)
    fixtures["negative_amount"] = neg_file

    # 5. Empty CSV fixture
    empty_file = out_path / "empty.csv"
    empty_file.write_text("")
    fixtures["empty"] = empty_file

    return fixtures


if __name__ == "__main__":
    generated = create_sample_fixtures()
    print(f"Created {len(generated)} sample fixtures:")
    for k, p in generated.items():
        print(f"  - {k}: {p}")
